import path from 'node:path';
import { extTest as test, expectExt as expect } from './helpers/ext-fixture';
import { seedSettings } from './helpers/ext-control';
import { advancedSettings, chooseModel, settingsTab, optionsLocale } from './helpers/options-ui';

test('split workspaces keep list and save controls stable, preserve drafts and reveal hidden errors', async ({ extContext, extensionId }) => {
  await seedSettings(extContext, extensionId, { uiLocale: 'zh-CN', apiBase: 'http://127.0.0.1:8080/v1' });
  const page = await extContext.newPage();
  await page.setViewportSize({ width: 1440, height: 960 });
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.goto(`chrome-extension://${extensionId}/options.html#section-sites`);
  await expect(page).toHaveTitle(/TapTranslate/);
  await expect(page.locator('[data-site-host]')).toHaveCount(7);
  await expect(page.locator('.site-card:visible')).toHaveCount(1);
  const footer = await page.locator('#stickyActions').boundingBox();
  const list = await page.locator('#siteList').boundingBox();
  expect(footer!.y + footer!.height).toBeLessThanOrEqual(961);
  const github = page.locator('.site-card:visible');
  await github.locator('[data-editor-tab="content"]').click();
  await expect(page.locator('#saveBtn')).toBeDisabled();
  await github.locator('[data-rule-mode="content"]').selectOption('custom');
  await github.locator('[data-selectors="content"]').fill('[');
  await page.locator('[data-site-host="x.com"]').click();
  const x = page.locator('.site-card:visible');
  await x.locator('[data-editor-tab="content"]').click();
  await x.locator('[data-rule-mode="content"]').selectOption('custom');
  await x.locator('[data-selectors="content"]').fill('.first-host');
  await x.locator('.site-domain-select').selectOption('www.x.com');
  await expect(page.locator('.site-card:visible [data-rule-mode="content"]')).toHaveValue('inherit');
  await page.locator('.site-card:visible .site-domain-select').selectOption('x.com');
  await expect(page.locator('.site-card:visible [data-selectors="content"]')).toHaveValue('.first-host');
  await page.locator('#saveBtn').click();
  await expect(page.locator('.site-card:visible .site-domain-select')).toHaveValue('github.com');
  await expect(page.locator('.site-card:visible [data-selectors="content"]')).toBeFocused();
  await expect(page.locator('.content-error:visible')).toContainText('第 1 行');
  await page.locator('.site-card:visible [data-selectors="content"]').fill('.markdown-body');
  expect((await page.locator('#stickyActions').boundingBox())!.y).toBeCloseTo(footer!.y, 0);
  expect((await page.locator('#siteList').boundingBox())!.y).toBeCloseTo(list!.y, 0);
  if (process.env.TAP_TRANSLATE_QA_DIR) await page.screenshot({ path: path.join(process.env.TAP_TRANSLATE_QA_DIR, 'workspace-sites-desktop.png') });
  await settingsTab(page, 'connection');
  await page.locator('#model').fill('draft-model-one');
  await page.locator('#addModelBtn').click();
  await page.locator('#model').fill('draft-model-two');
  await advancedSettings(page);
  await page.locator('#temperature').fill('0.7');
  await chooseModel(page, 0);
  await expect(page.locator('#model')).toHaveValue('draft-model-one');
  await chooseModel(page, 1);
  await expect(page.locator('#temperature')).toHaveValue('0.7');
  expect((await page.locator('#stickyActions').boundingBox())!.y).toBeCloseTo(footer!.y, 0);
  await page.locator('#saveBtn').click();
  await expect(page.locator('#saveStatus')).toContainText('已保存');
  if (process.env.TAP_TRANSLATE_QA_DIR) await page.screenshot({ path: path.join(process.env.TAP_TRANSLATE_QA_DIR, 'workspace-services-desktop.png') });
  await settingsTab(page, 'sites');
  await page.locator('#siteSearch').fill('www.x.com');
  await expect(page.locator('[data-site-host]')).toHaveCount(1);
  await expect(page.locator('#saveBtn')).toBeDisabled();
  await page.locator('[data-site-host="x.com"]').click();
  await page.locator('.site-card:visible [data-editor-tab="preferences"]').focus();
  await page.keyboard.press('ArrowRight');
  await expect(page.locator('.site-card:visible [data-editor-tab="content"]')).toBeFocused();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.site-card:visible .workspace-back').click();
  await expect(page.locator('#siteList')).toBeVisible();
  await page.locator('[data-site-host="x.com"]').click();
  await expect(page.locator('#siteList')).toBeHidden();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth && document.documentElement.scrollHeight <= innerHeight)).toBe(true);
  const { AxeBuilder } = await import('@axe-core/playwright');
  expect((await new AxeBuilder({ page }).analyze()).violations.filter(v => v.impact === 'serious' || v.impact === 'critical')).toEqual([]);
  if (process.env.TAP_TRANSLATE_QA_DIR) await page.screenshot({ path: path.join(process.env.TAP_TRANSLATE_QA_DIR, 'workspace-sites-mobile.png') });
  await settingsTab(page, 'connection');
  await chooseModel(page, 0);
  if (process.env.TAP_TRANSLATE_QA_DIR) await page.screenshot({ path: path.join(process.env.TAP_TRANSLATE_QA_DIR, 'workspace-services-mobile.png') });
  for (const locale of ['en', 'fr', 'es', 'ru', 'zh-TW', 'zh-CN']) {
    await optionsLocale(page, locale);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), locale).toBe(true);
  }
  await page.emulateMedia({ colorScheme: 'dark' });
  expect((await new AxeBuilder({ page }).analyze()).violations.filter(v => v.impact === 'serious' || v.impact === 'critical')).toEqual([]);
  for (const viewport of [{ width: 390, height: 500 }, { width: 844, height: 390 }, { width: 320, height: 568 }]) {
    await page.setViewportSize(viewport);
    await settingsTab(page, 'sites');
    const card = page.locator('.site-card:visible');
    await card.locator('[data-editor-tab="content"]').click();
    expect((await card.locator('.workspace-editor-body').boundingBox())!.height).toBeGreaterThan(170);
    await card.locator('[data-selectors="content"]').fill(`.height-${viewport.height}`);
    await expect(card.locator('[data-selectors="content"]')).toBeFocused();
    await expect(page.locator('#saveBtn')).toBeInViewport();
    await page.locator('#saveBtn').click();
    await expect(page.locator('#saveStatus')).toContainText('已保存');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await settingsTab(page, 'connection');
    await page.locator('#serviceEditor [data-editor-tab="basic"]').click();
    expect((await page.locator('#serviceEditor .workspace-editor-body').boundingBox())!.height).toBeGreaterThan(120);
    await page.locator('#model').fill(`short-model-${viewport.height}`);
    await expect(page.locator('#saveBtn')).toBeInViewport();
    await page.locator('#saveBtn').click();
    await expect(page.locator('#saveStatus')).toContainText('已保存');
  }
  expect(errors).toEqual([]);
});
