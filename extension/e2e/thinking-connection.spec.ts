import { optionsLocale, advancedSettings, chooseModel, showServiceField } from './helpers/options-ui';
import { extTest as test, expectExt as expect } from './helpers/ext-fixture';
import { startMockServer } from './helpers/mock-server';
import path from 'node:path';

test('MiniMax thinking controls, custom mapping and validation survive model switching', async ({ extContext, extensionId }) => {
  const mock = await startMockServer();
  try {
    const page = await extContext.newPage();
    const errors: string[] = [];
    const requests: Record<string, unknown>[] = [];
    page.on('pageerror', (error) => errors.push(error.message));
    page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
    page.on('request', (request) => { if (request.url().endsWith('/chat/completions')) requests.push(request.postDataJSON()); });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto(`chrome-extension://${extensionId}/options.html`);
    await expect(page).toHaveTitle(/TapTranslate/);
    await optionsLocale(page, 'zh-CN');
    await advancedSettings(page);
    await showServiceField(page, '#apiBase');
    await page.locator('#apiBase').fill(mock.apiBase);
    await showServiceField(page, '#apiKey');
    await page.locator('#apiKey').fill('e2e-only');
    await showServiceField(page, '#model');
    await page.locator('#model').fill('MiniMax-M3');
    await expect(page.locator('#thinkingHint')).toContainText('默认关闭');
    await expect(page.locator('#reasoningEffort')).toBeDisabled();
    await showServiceField(page, '#thinking');
    await page.locator('#thinking').selectOption('enabled');
    await page.locator('#testConnectionBtn').click();
    await expect(page.locator('#testConnectionStatus')).toContainText('已连接');
    expect(requests.at(-1)).toMatchObject({ thinking: { type: 'adaptive' }, max_tokens: 4096 });

    await showServiceField(page, '#thinking');
    await page.locator('#thinking').selectOption('disabled');
    await showServiceField(page, '#model');
    await page.locator('#model').fill('MiniMax-M3.1-Flash-Preview');
    await expect(page.locator('#thinking option[value="disabled"]')).toBeDisabled();
    await expect(page.locator('#thinkingError')).toContainText('无法关闭');
    const countBefore = requests.length;
    await page.locator('#testConnectionBtn').click();
    await expect(page.locator('#testConnectionStatus')).toContainText('无法关闭');
    expect(requests).toHaveLength(countBefore);
    await showServiceField(page, '#thinking');
    await page.locator('#thinking').selectOption('auto');
    await expect(page.locator('#thinkingError')).toBeHidden();
    await expect(page.locator('#reasoningEffort')).toBeEnabled();
    await showServiceField(page, '#reasoningEffort');
    await page.locator('#reasoningEffort').selectOption('max');
    await page.locator('#testConnectionBtn').click();
    await expect(page.locator('#testConnectionStatus')).toContainText('已连接');
    expect(requests.at(-1)).toMatchObject({ thinking: { type: 'adaptive' }, reasoning_effort: 'max' });

    await advancedSettings(page);
    if (process.env.TAP_TRANSLATE_QA_DIR) await page.locator('.model-settings').screenshot({ path: path.join(process.env.TAP_TRANSLATE_QA_DIR, 'thinking-flash-desktop.png'), style: '#stickyActions { visibility: hidden; }' });
    await showServiceField(page, '#thinkingAdapter');
    await page.locator('#thinkingAdapter').selectOption('custom');
    await expect(page.locator('#thinkingCustomFields')).toBeVisible();
    await expect(page.locator('#reasoningEffort')).toBeDisabled();
    await showServiceField(page, '#thinkingEnabledBody');
    await page.locator('#thinkingEnabledBody').fill('{"reasoning":{"enabled":true,"effort":"high"}}');
    await showServiceField(page, '#thinkingDisabledBody');
    await page.locator('#thinkingDisabledBody').fill('{"reasoning":{"enabled":false}}');
    await showServiceField(page, '#thinking');
    await page.locator('#thinking').selectOption('disabled');
    await page.locator('#testConnectionBtn').click();
    await expect(page.locator('#testConnectionStatus')).toContainText('已连接');
    expect(requests.at(-1)?.reasoning).toEqual({ enabled: false });
    expect(requests.at(-1)?.thinking).toBeUndefined();
    expect(requests.at(-1)?.reasoning_effort).toBeUndefined();

    await showServiceField(page, '#thinkingDisabledBody');
    await page.locator('#thinkingDisabledBody').fill('{"stream":true}');
    await expect(page.locator('#thinkingError')).toContainText('不可覆盖');
    await page.locator('#addModelBtn').click();
    await showServiceField(page, '#model');
    await page.locator('#model').fill('another-model');
    await page.locator('#saveBtn').click();
    await expect(page.locator('#model')).toHaveValue('MiniMax-M3.1-Flash-Preview');
    await expect(page.locator('#thinkingDisabledBody')).toHaveValue('{"stream":true}');
    await showServiceField(page, '#thinkingDisabledBody');
    await page.locator('#thinkingDisabledBody').fill('{"reasoning":{"enabled":false}}');
    await page.locator('#saveBtn').click();
    await expect(page.locator('#saveStatus')).toContainText('已保存');
    await page.reload();
    await expect(page.locator('#model')).toHaveValue('another-model');
    await chooseModel(page, 0);
    await advancedSettings(page);
    await expect(page.locator('#thinkingAdapter')).toHaveValue('custom');
    expect(JSON.parse(await page.locator('#thinkingDisabledBody').inputValue())).toEqual({ reasoning: { enabled: false } });
    await expect(page.locator('#thinking')).toHaveValue('disabled');
    await page.locator('#thinkingCustomFields').scrollIntoViewIfNeeded();
    if (process.env.TAP_TRANSLATE_QA_DIR) await page.locator('.thinking-settings').screenshot({ path: path.join(process.env.TAP_TRANSLATE_QA_DIR, 'thinking-custom-desktop.png'), style: '#stickyActions { visibility: hidden; }' });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('#thinkingAdapter').scrollIntoViewIfNeeded();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    if (process.env.TAP_TRANSLATE_QA_DIR) await page.screenshot({ path: path.join(process.env.TAP_TRANSLATE_QA_DIR, 'thinking-custom-mobile.png') });
    await showServiceField(page, '#resetModelBtn');
    await page.locator('#resetModelBtn').click();
    await expect(page.locator('#thinkingAdapter')).toHaveValue('auto');
    await expect(page.locator('#thinkingCustomFields')).toBeHidden();
    await expect(page.locator('#thinking')).toHaveValue('auto');
    await expect(page.locator('#thinking option[value="disabled"]')).toBeDisabled();
    expect(errors).toEqual([]);
  } finally {
    await mock.close();
  }
});
